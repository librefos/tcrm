#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "postgres" <<-EOSQL
  CREATE USER "$RELATICLE_USER" WITH PASSWORD '$RELATICLE_PASSWORD';
  CREATE USER "$CHATWOOT_USER" WITH PASSWORD '$CHATWOOT_PASSWORD';
  CREATE USER "$N8N_USER" WITH PASSWORD '$N8N_PASSWORD';
  CREATE USER "$EVOLUTION_USER" WITH PASSWORD '$EVOLUTION_PASSWORD';

  CREATE DATABASE "$RELATICLE_DB" OWNER "$RELATICLE_USER";
  CREATE DATABASE "$CHATWOOT_DB" OWNER "$CHATWOOT_USER";
  CREATE DATABASE "$N8N_DB" OWNER "$N8N_USER";
  CREATE DATABASE "$EVOLUTION_DB" OWNER "$EVOLUTION_USER";
EOSQL

